"""Source-conversion transforms shared by the GH3 venue adapters."""

import math

import numpy as np


def angles_matrix(angles):
    x, y, z = angles
    cx, sx = math.cos(x), math.sin(x)
    cy, sy = math.cos(y), math.sin(y)
    cz, sz = math.cos(z), math.sin(z)
    matrix = np.array([[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]]) @ np.array([[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]]) @ np.array([[1, 0, 0], [0, cx, -sx], [0, sx, cx]])
    reflect = np.diag([1, 1, -1])
    return reflect @ matrix @ reflect
