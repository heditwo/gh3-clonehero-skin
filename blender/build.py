"""Build the CH Stage Tools Blender extension zip.

The add-on and the converter share one validator: this step copies pipeline/package and schemas/ into
chstage_tools/vendor/package_format/ (not in git), then zips the extension.

Usage: python blender/build.py [--output DIR] [--vendor-only]
"""

import argparse
import re
import shutil
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
ADDON = HERE / "chstage_tools"
VENDOR = ADDON / "vendor"
VALIDATOR_FILES = ("__init__.py", "chains.py", "character.py", "container.py", "decisions.py", "glb.py", "humanoid.py", "q48.py", "retarget_check.py", "schema.py", "skeleton.py", "texture.py", "validate.py")
DATE = (2026, 1, 1, 0, 0, 0)


def vendor():
    """Copy the package validator and the schemas into the add-on."""
    if VENDOR.exists(): shutil.rmtree(VENDOR)
    target = VENDOR / "package_format"
    (target / "schemas").mkdir(parents=True)
    (VENDOR / "__init__.py").write_text('"""Generated by blender/build.py from pipeline/package and schemas/. Do not edit."""\n')
    for name in VALIDATOR_FILES:
        source = (ROOT / "pipeline" / "package" / name).read_text()
        if re.search(r"^\s*(from|import) pipeline", source, re.MULTILINE):
            raise SystemExit(f"pipeline/package/{name} imports outside the package; the add-on cannot bundle it")
        (target / name).write_text(source)
    for schema in sorted((ROOT / "schemas").glob("*.schema.json")):
        shutil.copyfile(schema, target / "schemas" / schema.name)
    return target


def version():
    match = re.search(r'^version = "([^"]+)"', (ADDON / "blender_manifest.toml").read_text(), re.MULTILINE)
    return match.group(1)


def files():
    for path in sorted(ADDON.rglob("*")):
        relative = path.relative_to(ADDON)
        if path.is_file() and "__pycache__" not in relative.parts and path.suffix != ".pyc":
            yield path, relative.as_posix()


def build(output):
    vendor()
    output.mkdir(parents=True, exist_ok=True)
    archive = output / f"chstage_tools-{version()}.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as bundle:
        for path, name in files():
            info = zipfile.ZipInfo(name, DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            bundle.writestr(info, path.read_bytes())
    return archive


def main(argv=None):
    parser = argparse.ArgumentParser(prog="python blender/build.py", description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=HERE / "dist")
    parser.add_argument("--vendor-only", action="store_true", help="only refresh chstage_tools/vendor (for a development install)")
    args = parser.parse_args(argv)
    if args.vendor_only: print(vendor())
    else: print(build(args.output))


if __name__ == "__main__":
    sys.exit(main())
